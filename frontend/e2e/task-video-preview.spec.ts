import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { randomUUID } from "node:crypto";

test("task navigation returns to its shot and video previews follow actual media dimensions", async ({ page, request }, testInfo) => {
  const project = await (await request.post("/api/projects", { data: { name: "视频预览验收" } })).json();
  const draftID = randomUUID();
  const draft = { id: draftID, name: "预览草稿", version: 0, story: { body: "庭院人物", scenes: [{ id: "shot", order: 1, title: "庭院人物", visual_prompt: "人物回眸", duration_seconds: 5 }] } };
  expect((await request.post(`/api/projects/${project.id}/drafts`, { data: draft })).ok()).toBeTruthy();
  const shotURL = `/studio/${project.id}/${draftID}/shots/shot`;
  const task = { id: "preview-task", project_id: project.id, draft_id: draftID, scene_id: "shot", run_id: "preview-run", kind: "video", status: "succeeded", stage: "completed", progress: 100, input: { prompt: "人物回眸" }, result_url: "/media/generated-preview-task.mp4", created_at: "2026-10-10T07:00:00Z" };
  const run = { id: task.run_id, scene_id: "shot", state: "awaiting_video_selection", task_ids: [task.id], snapshot_id: "snapshot", video_model_id: "测试视频模型", resolution: "720P", duration_seconds: 5, created_at: task.created_at, steps: [task], selection: { speech_take_ids: {} }, plan: [{ path: "reference_video", aspect_ratio: "16:9", video_input_mode: "first_frame", prompt: "人物回眸", entities: [] }] };
  let media = readFileSync(join(process.cwd(), "e2e/fixtures/preview-square.webm"));
  await page.route("**/media/generated-preview-task.mp4", r => r.fulfill({ contentType: "video/webm", body: media }));
  await page.route("**/api/tasks?limit=100", r => r.fulfill({ json: { tasks: [task, { ...task, id: "deleted-shot-task", scene_id: "deleted", result_url: "" }], total: 2 } }));
  const runEndpoint = `/api/projects/${project.id}/drafts/${draftID}/scenes/shot/generation-runs`;
  await page.route(`**${runEndpoint}`, r => r.fulfill({ json: { runs: [run] } }));
  await page.route(`**${runEndpoint}/${task.run_id}`, r => r.fulfill({ json: run }));
  await page.route(`**/api/projects/${project.id}/drafts/${draftID}`, r => r.fulfill({ json: { ...draft, video_versions: [{ id: "version", task_id: task.id, scene_id: "shot", local_media_path: task.result_url, duration_seconds: 5, input_fingerprint: "test" }] } }));
  await page.route(`**${runEndpoint}/${task.run_id}/selected-media`, async r => {
    expect(r.request().postDataJSON().video_version_id).toBe("version");
    await r.fulfill({ json: { ...run, state: "awaiting_composition", selection: { video_version_id: "version" } } });
  });
  await page.goto("/tasks");
  const card = page.locator(".task-detail").filter({ has: page.getByRole("link", { name: "返回分镜", exact: true }) });
  await expect(card).toHaveCount(1);
  await expect(page.locator(".task-detail").filter({ hasText: "原镜头已删除" }).getByRole("link", { name: "返回分镜" })).toHaveCount(0);
  await card.getByRole("link", { name: "返回分镜", exact: true }).click();
  await expect(page).toHaveURL(shotURL);
  await page.goto("/tasks");
  await card.getByRole("link", { name: "查看任务详情" }).click();
  await expect(page).toHaveURL(`${shotURL}/runs/${task.run_id}`);
  const video = page.locator(".run-step video");
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.videoWidth)).toBe(360);
  let bounds = (await video.boundingBox())!;
  expect(Math.abs(bounds.width / bounds.height - 1)).toBeLessThan(0.02);
  expect(bounds.width).toBeLessThanOrEqual(520);
  expect(bounds.height).toBeGreaterThan(240);
  await expect(video).toHaveAttribute("controls", "");
  await video.evaluate((v: HTMLVideoElement) => v.play());
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.currentTime)).toBeGreaterThan(0);
  await video.evaluate((v: HTMLVideoElement) => v.pause());
  await page.screenshot({ path: testInfo.outputPath("video-detail-square.png"), fullPage: true });
  await expect(page.getByRole("button", { name: "下载视频", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: "选用此结果", exact: true }).click();
  await expect(page.getByRole("button", { name: "已选用", exact: true })).toBeDisabled();
  await page.getByRole("link", { name: "返回分镜", exact: true }).click();
  await expect(page).toHaveURL(shotURL);
  media = readFileSync(join(process.cwd(), "e2e/fixtures/preview-portrait.webm"));
  await page.goto(`${shotURL}/runs/${task.run_id}`);
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.videoHeight)).toBe(320);
  bounds = (await video.boundingBox())!;
  expect(Math.abs(bounds.width / bounds.height - 9/16)).toBeLessThan(0.02);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("link", { name: "返回分镜", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  bounds = (await video.boundingBox())!;
  expect(Math.abs(bounds.width / bounds.height - 9/16)).toBeLessThan(0.02);
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.readyState)).toBeGreaterThanOrEqual(2);
  await page.screenshot({ path: testInfo.outputPath("video-detail-mobile.png"), fullPage: true });
});
